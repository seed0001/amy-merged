QUESTION_BANKS = {"rule": "ask_rule", "category": "ask_category", "differences": "ask_differences",
                  "current": "ask_current", "distinguish": "ask_distinguish", "meaning": "ask_meaning"}


def default_pick(key, bank=None, **fields):
    return random.choice(bank or BANKS[key]).format(**fields)


def say(pick, key, **fields):
    return pick("thought:" + key, BANKS[key], **fields)


def question(pick, chain):
    ask = getattr(chain, "ask", None) or {}
    key = QUESTION_BANKS.get(ask.get("kind"))
    if key is None:
        return chain.question
    return say(pick, key, **{k: v for k, v in ask.items() if k != "kind"})
